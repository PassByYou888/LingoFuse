%% =========================================================================
%% API registration
%% =========================================================================

%% Register a Call API in ASYNC mode. The pid receives
%% {lf_call, ApiName, Payload} and the C callback returns
%% immediately. This is the original binding behaviour and is kept
%% unchanged for backward compatibility. Use register_call_sync/4
%% when the caller needs a synchronous output writeback.
-spec register_call(app_handle(), api_name(), binary(), pid()) ->
    ok | {error, term()}.
register_call(App, Name, Desc, Pid)
        when is_reference(App), is_binary(Name), is_binary(Desc),
             is_pid(Pid) ->
    normalize_ok(lingofuse_nif:register_call(App, Name, Desc, Pid));
register_call(_, _, _, _) ->
    error(badarg).

%% Register a Call API in SYNC mode. The pid receives
%% {lf_call, Ref, ApiName, Payload} and MUST call reply/2 with the
%% same Ref and a binary result. The C callback blocks until either
%% the reply arrives or the sync timeout expires.
-spec register_call_sync(app_handle(), api_name(), binary(), pid()) ->
    ok | {error, term()}.
register_call_sync(App, Name, Desc, Pid)
        when is_reference(App), is_binary(Name), is_binary(Desc),
             is_pid(Pid) ->
    normalize_ok(lingofuse_nif:register_call_sync(App, Name, Desc, Pid));
register_call_sync(_, _, _, _) ->
    error(badarg).

%% Register a Notify API. The pid receives {lf_notify, ApiName,
%% Payload} on every incoming notification. There is no reply path.
-spec register_notify(app_handle(), api_name(), binary(), pid()) ->
    ok | {error, term()}.
register_notify(App, Name, Desc, Pid)
        when is_reference(App), is_binary(Name), is_binary(Desc),
             is_pid(Pid) ->
    normalize_ok(lingofuse_nif:register_notify(App, Name, Desc, Pid));
register_notify(_, _, _, _) ->
    error(badarg).

-spec unregister(app_handle(), api_name()) ->
    {ok, boolean()} | {error, term()}.
unregister(App, Name) when is_reference(App), is_binary(Name) ->
    case lingofuse_nif:unregister(App, Name) of
        true  -> {ok, true};
        false -> {ok, false};
        {error, Reason} -> {error, Reason}
    end;
unregister(_, _) ->
    error(badarg).

%% =========================================================================
%% Sync callback bridge
%% =========================================================================

%% Deliver the result of a sync Call callback to the blocked C
%% callback identified by Ref. The payload is written verbatim into
%% the LingoFuse output handle.
%%
%% Returns {error, unknown_ref} when:
%%   - the ref does not correspond to any pending request, or
%%   - the pending request has already timed out on the C side.
%%
%% In both cases the caller may safely ignore the error.
-spec reply(sync_ref(), binary()) -> ok | {error, term()}.
reply(Ref, ResultBin)
        when is_integer(Ref), Ref >= 0, is_binary(ResultBin) ->
    normalize_ok(lingofuse_nif:reply(Ref, ResultBin));
reply(_, _) ->
    error(badarg).

%% Change the process-wide sync callback timeout, in milliseconds.
%% Values below 100 ms are clamped to 100 ms by the C side. The
%% default is 30000 ms.
-spec set_sync_timeout(pos_integer()) -> ok | {error, term()}.
set_sync_timeout(Ms) when is_integer(Ms), Ms > 0 ->
    normalize_ok(lingofuse_nif:set_sync_timeout(Ms));
set_sync_timeout(_) ->
    error(badarg).

%% Return the current sync callback timeout, in milliseconds.
-spec get_sync_timeout() -> {ok, pos_integer()} | {error, term()}.
get_sync_timeout() ->
    normalize_ok(lingofuse_nif:get_sync_timeout()).

