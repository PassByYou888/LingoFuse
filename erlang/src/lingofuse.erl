%% =========================================================================
%% NIF availability
%% =========================================================================

-spec ensure_loaded() -> ok | {error, lf_not_loaded}.
ensure_loaded() ->
    try lingofuse_nif:check_main_thread() of
        _ -> ok
    catch
        error:{not_loaded, _} -> {error, lf_not_loaded};
        error:undef           -> {error, lf_not_loaded}
    end.

