%% src/lingofuse.erl
%%
%% Public Erlang API for the LingoFuse binding.
%%
%% Every function normalizes the NIF result to {ok, Value} or
%% {error, Reason}, or to ok on success. Argument errors raise badarg.
%%
%% Call callback modes
%% -------------------
%% Two modes are supported:
%%
%%   register_call/4        ASYNC. The registered pid receives
%%                          {lf_call, ApiName, Payload}. The C
%%                          callback returns immediately; the
%%                          LingoFuse output handle is empty. This
%%                          is the original binding behaviour.
%%
%%   register_call_sync/4   SYNC. The registered pid receives
%%                          {lf_call, Ref, ApiName, Payload}. The
%%                          C callback BLOCKS until the pid calls
%%                          reply(Ref, ResultBin) with a binary.
%%                          The payload is written into the
%%                          LingoFuse output handle, so the caller
%%                          of call/3 / local_call/2 sees a normal
%%                          synchronous response.
%%
%%                          If the pid never replies, the C callback
%%                          unblocks after the sync timeout (default
%%                          30000 ms, configurable with
%%                          set_sync_timeout/1) and the output
%%                          handle is left empty.
%%
%%                          A late reply after a timeout returns
%%                          {error, unknown_ref}.
%%
%%   register_notify/4      NOTIFY. The registered pid receives
%%                          {lf_notify, ApiName, Payload}. There is
%%                          no reply path in notify mode.
%%
%% The Ref in a sync message is an opaque non-negative integer
%% generated by the C layer. Callers must pass it back verbatim to
%% reply/2.

