%% =========================================================================
%% Internal helpers
%% =========================================================================

wrap_handle(Value) ->
    try
        case Value of
            {error, _} = Err -> Err;
            Term when is_reference(Term) -> {ok, Term};
            Term -> {ok, Term}
        end
    catch
        error:{not_loaded, _} -> {error, lf_not_loaded}
    end.

normalize_ok(Value) ->
    try
        case Value of
            ok              -> ok;
            {error, _} = E  -> E;
            Term            -> {ok, Term}
        end
    catch
        error:{not_loaded, _} -> {error, lf_not_loaded}
    end.