//! 32-byte LingoFuse P2P session identifier.
//!
//! The C ABI exposes the P2P identity as `TP2P_UID___`, which is
//! `array[0..31] of Byte` on the Pascal side. The C header wraps it in a
//! `struct { uint8_t bytes[32]; }` (`TP2P_UID`) so that it can be passed
//! by value across the cdecl boundary.
//!
//! At the Rust level, [`Uid`] is a newtype over `[u8; 32]` with:
//!
//! - `Copy`, `Eq`, `Hash`, `Default`
//! - `Debug` (short hex form) and `Display` (full 64-character hex)
//! - hex and slice constructors with validation
//!
//! # ABI note
//!
//! The same Pascal type plays TWO distinct roles at the C ABI:
//!
//! | Role     | Where it appears                              | C type             |
//! |----------|-----------------------------------------------|--------------------|
//! | Argument | `LF_UID_Call`, `LF_Check_UID`, ...            | `TP2P_UID` (value) |
//! | Return   | `LF_Get_P2P_UID`                              | `const TP2P_UID*`  |
//!
//! Both roles are unified at the Rust level by [`Uid`]:
//!
//! - **Argument role**: `uid.to_lf()` produces the `#[repr(C)]` struct
//!   that the native layer expects **by value**.
//! - **Return role**: `Uid::from_ptr(ptr)` **copies** the 32 bytes out
//!   of the transient library-owned buffer. The raw pointer is never
//!   exposed to user code.
//!
//! The two conversion helpers (`to_lf` / `from_ptr`) are added in a
//! later upgrade batch, once `sys::LfP2PUid` is defined. This file is
//! FFI-free on purpose so that it can be reviewed and tested in
//! isolation.
//!
//! # Session semantics
//!
//! A UID is generated by the native library when a client first
//! establishes a tunnel, and it is **regenerated on every reconnect**.
//! It is therefore a session-level identifier, not a stable device ID.
//! Caching a UID across a link loss is unsafe; callers that cache must
//! re-probe after a reconnect.
//!
//! # Side-data semantics
//!
//! Inside a Call / Notify callback, a UID obtained from
//! `DataHandle::p2p_uid()` identifies the **sender** of that request.
//! It is injected into the payload header by the sender's transport
//! layer, so it is only meaningful on the *input* handle of a callback.
//! See the `DataHandle` documentation for the full contract.
//!
//! # Example
//!
//! ```
//! use lingofuse::uid::Uid;
//!
//! // 64 hex characters, with or without a `0x` prefix.
//! let uid = Uid::from_hex(
//!     "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef"
//! ).unwrap();
//!
//! assert_eq!(uid.to_hex().len(), 64);
//! assert!(!uid.is_null());
//! assert_eq!(Uid::NULL.to_string(), "0".repeat(64));
//! ```

use std::fmt;

// ============================================================================
// Constants
// ============================================================================

/// Length in bytes of a P2P UID.
pub const UID_LEN: usize = 32;

/// Length in characters of the hex representation of a UID.
pub const UID_HEX_LEN: usize = UID_LEN * 2;

// ============================================================================
// Uid
// ============================================================================

/// A 32-byte LingoFuse P2P session identifier.
///
/// See the module documentation for the ABI roles, the session semantics,
/// and the side-data semantics.
///
/// # Traits
///
/// - `Copy` and `Eq`: the type is a plain value, freely copyable.
/// - `Hash`: usable as a `HashMap` / `HashSet` key.
/// - `Default`: `Uid::NULL`.
/// - `Debug`: short form, e.g. `Uid(01234567..89abcdef)` or `Uid(NULL)`.
/// - `Display`: full 64-character lowercase hex, no prefix.
#[derive(Clone, Copy, PartialEq, Eq, Hash)]
pub struct Uid([u8; UID_LEN]);

impl Uid {
    /// The null UID: 32 zero bytes.
    ///
    /// Returned by `DataHandle::p2p_uid()` when the handle is not an
    /// input handle, and by `LF_Get_P2P_UID` when the identity has not
    /// been injected. It is also a valid value in the argument role: it
    /// will simply match no target.
    pub const NULL: Uid = Uid([0u8; UID_LEN]);

    /// Builds a `Uid` from a fixed-size byte array.
    #[inline]
    pub const fn from_bytes(bytes: [u8; UID_LEN]) -> Self {
        Uid(bytes)
    }

    /// Builds a `Uid` from a byte slice.
    ///
    /// # Errors
    ///
    /// Returns
    /// [`ErrorCode::InvalidArgument`](crate::error::ErrorCode::InvalidArgument)
    /// if the slice length is not exactly [`UID_LEN`].
    pub fn from_slice(slice: &[u8]) -> Result<Self, crate::error::Error> {
        if slice.len() != UID_LEN {
            return Err(crate::error::Error::invalid_argument(
                "Uid::from_slice",
                format!("expected {} bytes, got {}", UID_LEN, slice.len()),
            ));
        }
        let mut buf = [0u8; UID_LEN];
        buf.copy_from_slice(slice);
        Ok(Uid(buf))
    }

    /// Builds a `Uid` from a 64-character hex string.
    ///
    /// Accepts uppercase and lowercase hex digits. A leading `0x` or `0X`
    /// prefix is optional and stripped before validation.
    ///
    /// # Errors
    ///
    /// Returns
    /// [`ErrorCode::InvalidArgument`](crate::error::ErrorCode::InvalidArgument)
    /// if the input is not exactly 64 hex digits (after an optional
    /// prefix), or if any character is not a hex digit.
    pub fn from_hex(s: &str) -> Result<Self, crate::error::Error> {
        let s = s
            .strip_prefix("0x")
            .or_else(|| s.strip_prefix("0X"))
            .unwrap_or(s);

        if s.len() != UID_HEX_LEN {
            return Err(crate::error::Error::invalid_argument(
                "Uid::from_hex",
                format!(
                    "expected {} hex characters, got {}",
                    UID_HEX_LEN,
                    s.len()
                ),
            ));
        }

        let bytes = s.as_bytes();
        let mut buf = [0u8; UID_LEN];
        for i in 0..UID_LEN {
            let hi = hex_nibble(bytes[i * 2]).ok_or_else(|| {
                crate::error::Error::invalid_argument(
                    "Uid::from_hex",
                    format!("invalid hex digit at position {}", i * 2),
                )
            })?;
            let lo = hex_nibble(bytes[i * 2 + 1]).ok_or_else(|| {
                crate::error::Error::invalid_argument(
                    "Uid::from_hex",
                    format!("invalid hex digit at position {}", i * 2 + 1),
                )
            })?;
            buf[i] = (hi << 4) | lo;
        }
        Ok(Uid(buf))
    }

    /// Returns a reference to the raw 32 bytes.
    #[inline]
    pub const fn as_bytes(&self) -> &[u8; UID_LEN] {
        &self.0
    }

    /// Copies the 32 bytes into a fresh array.
    #[inline]
    pub const fn to_bytes(self) -> [u8; UID_LEN] {
        self.0
    }

    /// Returns `true` when all 32 bytes are zero.
    #[inline]
    pub fn is_null(&self) -> bool {
        self.0.iter().all(|&b| b == 0)
    }

    /// Encodes the UID as 64 lowercase hex characters.
    ///
    /// The output contains no prefix and no separators.
    pub fn to_hex(&self) -> String {
        let mut out = String::with_capacity(UID_HEX_LEN);
        for &b in &self.0 {
            out.push(hex_char(b >> 4));
            out.push(hex_char(b & 0x0F));
        }
        out
    }
}

// ============================================================================
// Internal helpers
// ============================================================================

/// Maps a nibble value (0..=15) to its lowercase hex character.
///
/// The `_` arm is unreachable when the input comes from a `>> 4` or
/// `& 0x0F` operation, but is provided to keep the function total
/// without an `unsafe` assumption.
#[inline]
const fn hex_char(n: u8) -> char {
    match n {
        0..=9   => (b'0' + n) as char,
        10..=15 => (b'a' + (n - 10)) as char,
        _       => '?',
    }
}

/// Parses a single ASCII hex digit. Returns `None` for anything else.
#[inline]
fn hex_nibble(b: u8) -> Option<u8> {
    match b {
        b'0'..=b'9' => Some(b - b'0'),
        b'a'..=b'f' => Some(b - b'a' + 10),
        b'A'..=b'F' => Some(b - b'A' + 10),
        _           => None,
    }
}

// ============================================================================
// Trait implementations
// ============================================================================

impl Default for Uid {
    #[inline]
    fn default() -> Self {
        Uid::NULL
    }
}

impl From<[u8; UID_LEN]> for Uid {
    #[inline]
    fn from(bytes: [u8; UID_LEN]) -> Self {
        Uid(bytes)
    }
}

impl From<Uid> for [u8; UID_LEN] {
    #[inline]
    fn from(uid: Uid) -> Self {
        uid.0
    }
}

impl fmt::Display for Uid {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        // Full 64-character hex, no prefix, lowercase.
        for b in &self.0 {
            write!(f, "{:02x}", b)?;
        }
        Ok(())
    }
}

impl fmt::Debug for Uid {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        if self.is_null() {
            return f.write_str("Uid(NULL)");
        }

        // Short form: first 4 bytes, "..", last 4 bytes, all in hex.
        // This is a Debug convenience, not a stable wire format.
        let mut first = [0u8; 4];
        let mut last  = [0u8; 4];
        first.copy_from_slice(&self.0[..4]);
        last.copy_from_slice(&self.0[UID_LEN - 4..]);

        write!(
            f,
            "Uid({:02x}{:02x}{:02x}{:02x}..{:02x}{:02x}{:02x}{:02x})",
            first[0], first[1], first[2], first[3],
            last[0], last[1], last[2], last[3],
        )
    }
}

