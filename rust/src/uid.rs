#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn null_is_all_zero() {
        assert!(Uid::NULL.is_null());
        assert_eq!(Uid::NULL.to_bytes(), [0u8; UID_LEN]);
        assert_eq!(Uid::default(), Uid::NULL);
    }

    #[test]
    fn hex_roundtrip_lowercase() {
        let hex = "0123456789abcdef0123456789abcdef\
                   0123456789abcdef0123456789abcdef";
        let uid = Uid::from_hex(hex).unwrap();
        assert_eq!(uid.to_hex(), hex);
    }

    #[test]
    fn hex_roundtrip_uppercase() {
        let hex = "0123456789ABCDEF0123456789ABCDEF\
                   0123456789ABCDEF0123456789ABCDEF";
        let uid = Uid::from_hex(hex).unwrap();
        assert_eq!(uid.to_hex(), hex.to_lowercase());
    }

    #[test]
    fn hex_accepts_0x_prefix() {
        let hex = "0x0123456789abcdef0123456789abcdef\
                   0123456789abcdef0123456789abcdef";
        let uid = Uid::from_hex(hex).unwrap();
        assert_eq!(uid.to_hex(), &hex[2..]);
    }

    #[test]
    fn hex_accepts_0x_uppercase_prefix() {
        let hex = "0X0123456789abcdef0123456789abcdef\
                   0123456789abcdef0123456789abcdef";
        let uid = Uid::from_hex(hex).unwrap();
        assert_eq!(uid.to_hex(), &hex[2..]);
    }

    #[test]
    fn hex_rejects_wrong_length() {
        assert!(Uid::from_hex("").is_err());
        assert!(Uid::from_hex("abc").is_err());
        assert!(Uid::from_hex(&"a".repeat(63)).is_err());
        assert!(Uid::from_hex(&"a".repeat(65)).is_err());
    }

    #[test]
    fn hex_rejects_non_hex() {
        let bad = "zzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzz\
                   zzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzz";
        assert!(Uid::from_hex(bad).is_err());
    }

    #[test]
    fn from_slice_accepts_exact_len() {
        let bytes = [0xABu8; UID_LEN];
        let uid = Uid::from_slice(&bytes).unwrap();
        assert_eq!(uid.to_bytes(), bytes);
    }

    #[test]
    fn from_slice_rejects_short() {
        assert!(Uid::from_slice(&[0u8; UID_LEN - 1]).is_err());
    }

    #[test]
    fn from_slice_rejects_long() {
        assert!(Uid::from_slice(&[0u8; UID_LEN + 1]).is_err());
    }

    #[test]
    fn from_slice_rejects_empty() {
        assert!(Uid::from_slice(&[]).is_err());
    }

    #[test]
    fn array_roundtrip() {
        let arr = [0x42u8; UID_LEN];
        let uid: Uid = arr.into();
        let back: [u8; UID_LEN] = uid.into();
        assert_eq!(arr, back);
    }

    #[test]
    fn display_is_full_lowercase_hex() {
        let uid = Uid::from_bytes([0xFFu8; UID_LEN]);
        assert_eq!(uid.to_string(), "f".repeat(64));
    }

    #[test]
    fn debug_short_for_non_null() {
        let mut bytes = [0u8; UID_LEN];
        bytes[0] = 0x01;
        bytes[1] = 0x23;
        bytes[2] = 0x45;
        bytes[3] = 0x67;
        bytes[UID_LEN - 4] = 0x89;
        bytes[UID_LEN - 3] = 0xAB;
        bytes[UID_LEN - 2] = 0xCD;
        bytes[UID_LEN - 1] = 0xEF;
        let uid = Uid::from_bytes(bytes);
        assert_eq!(format!("{:?}", uid), "Uid(01234567..89abcdef)");
    }

    #[test]
    fn debug_null() {
        assert_eq!(format!("{:?}", Uid::NULL), "Uid(NULL)");
    }

    #[test]
    fn equality_and_hash() {
        use std::collections::HashSet;

        let a = Uid::from_bytes([1u8; UID_LEN]);
        let b = Uid::from_bytes([1u8; UID_LEN]);
        let c = Uid::from_bytes([2u8; UID_LEN]);

        assert_eq!(a, b);
        assert_ne!(a, c);

        let mut set = HashSet::new();
        set.insert(a);
        assert!(set.contains(&b));
        assert!(!set.contains(&c));
    }

    #[test]
    fn copy_semantics() {
        let a = Uid::from_bytes([7u8; UID_LEN]);
        let b = a;            // Copy, not move
        assert_eq!(a, b);     // `a` still usable
    }

    #[test]
    fn as_bytes_matches_to_bytes() {
        let uid = Uid::from_hex(
            "deadbeefdeadbeefdeadbeefdeadbeef\
             deadbeefdeadbeefdeadbeefdeadbeef",
        )
        .unwrap();
        assert_eq!(uid.as_bytes(), &uid.to_bytes());
    }
}