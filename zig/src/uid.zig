// =============================================================================
//  uid.zig - 32-byte LingoFuse P2P session identifier.
// -----------------------------------------------------------------------------
//  The C ABI exposes the P2P identity as `TP2P_UID`, a 32-byte struct
//  that plays two distinct roles:
//
//    ARGUMENT role
//        Functions such as `LF_UID_Call`, `LF_Check_UID`, `LF_WriteUid`,
//        and `LF_ReadUid` take the struct BY VALUE. The Zig-side
//        representation is `sys.P2PUid`, an `extern struct` whose
//        layout is guaranteed to match the C struct byte-for-byte.
//
//    RETURN role
//        `LF_Get_P2P_UID` returns a `const TP2P_UID*` pointing into a
//        library-owned transient buffer that is released about 5
//        seconds after the call. The Zig-side representation is
//        `?*const sys.P2PUid`.
//
//  `Uid` unifies both roles behind a single safe value type:
//
//    * `Uid.toLf()` produces the argument-role `extern struct`.
//    * `Uid.fromPtr(p)` copies the 32 bytes out of the return-role
//      pointer. The raw pointer is never exposed to the caller.
//
//  Session semantics
//  -----------------
//  A UID is generated by the native library when a client first
//  establishes a tunnel, and it is regenerated on every reconnect. It
//  is a session-level identifier, not a stable device ID. Caching a
//  UID across a link loss is unsafe; callers that cache must re-probe
//  after a reconnect.
//
//  Side-data semantics
//  -------------------
//  Inside a Call / Notify callback, a UID obtained from
//  `DataHandle.p2pUid()` identifies the SENDER of that request. It is
//  injected into the payload header by the sender's transport layer,
//  so it is only meaningful on the *input* handle of a callback.
//
//  Why not `[32]u8` directly
//  -------------------------
//  Using `[32]u8` as the public type would lose the ABI guarantee at
//  the argument position: FPC passes a 32-byte Pascal array by value on
//  the stack, and Zig must match that convention exactly. Wrapping the
//  bytes in an `extern struct` is the explicit declaration of that
//  contract, and it also gives us a natural place to hang the hex
//  helpers below.
//
//  Array-fill style
//  ----------------
//  This module deliberately uses `@splat` for every array-fill
//  operation, including in tests. `@splat` is a Zig builtin that has
//  no whitespace rules, in contrast to the `**` array-repeat operator,
//  which requires matching whitespace on both sides. Any tool that
//  normalises whitespace (an editor, a Markdown round-trip) can break
//  that rule silently; `@splat` cannot be broken that way.
//
//  Why no `format` method
//  ----------------------
//  Zig 0.17 changed the custom-formatting interface: `std.Io.Writer`
//  is a new opaque writer type, and the old
//  `fn format(self, comptime fmt, options, writer: anytype)` signature
//  is no longer detected by `std.fmt.bufPrint` / `std.debug.print`.
//  Rather than pin the binding to a specific Zig minor version by
//  guessing the current signature, this module exposes the UID in hex
//  via `toHexBuf` and `toHexAlloc`. Callers that want a debug string
//  do:
//
//      var buf: [64]u8 = undefined;
//      uid.toHexBuf(&buf);
//      std.debug.print("uid = {s}\n", .{&buf});
//
//  This keeps `Uid` usable across Zig versions without a formatting
//  shim.
// =============================================================================

const std = @import("std");
const sys = @import("sys.zig");
const Error = @import("error.zig").Error;
const util = @import("util.zig");

// =============================================================================
// Constants
// =============================================================================

/// Length in bytes of a P2P UID.
pub const UID_LEN: usize = 32;

/// Length in characters of the hex representation of a UID.
pub const UID_HEX_LEN: usize = UID_LEN * 2;

// =============================================================================
// Uid
// =============================================================================

/// A 32-byte LingoFuse P2P session identifier.
///
/// See the module docstring for the ABI roles, session semantics, and
/// side-data semantics.
///
/// # Traits
///
/// `Uid` is a plain value type: it is `Copy`, and `Eq` by byte
/// comparison. There is no `Default` and no custom `format` method;
/// use `Uid.NULL` and `toHexBuf` / `toHexAlloc` explicitly.
pub const Uid = struct {
    const Self = @This();

    /// The wire representation. Kept private so that all reads and
    /// writes go through the safe API below.
    inner: sys.P2PUid,

    /// The null UID: 32 zero bytes.
    ///
    /// Returned by `DataHandle.p2pUid()` when the handle is not an
    /// input handle, and by `LF_Get_P2P_UID` when the identity has not
    /// been injected. It is also a valid argument in UID-addressed
    /// calls: it simply matches no target.
    pub const NULL: Self = .{ .inner = sys.P2PUid.NULL };

    // -------------------------------------------------------------------------
    // Construction
    // -------------------------------------------------------------------------

    /// Build a `Uid` from a fixed-size byte array.
    pub fn fromBytes(bytes: [UID_LEN]u8) Self {
        return .{ .inner = .{ .bytes = bytes } };
    }

    /// Build a `Uid` from a byte slice.
    ///
    /// # Errors
    ///
    /// Returns `Error.InvalidArgument` when the slice length is not
    /// exactly `UID_LEN`.
    pub fn fromSlice(slice: []const u8) Error!Self {
        if (slice.len != UID_LEN) return Error.InvalidArgument;
        var bytes: [UID_LEN]u8 = undefined;
        @memcpy(&bytes, slice);
        return .{ .inner = .{ .bytes = bytes } };
    }

    /// Build a `Uid` from a 64-character hex string.
    ///
    /// Accepts uppercase and lowercase hex digits. A leading `0x` or
    /// `0X` prefix is optional and stripped before validation.
    ///
    /// # Errors
    ///
    /// Returns `Error.InvalidArgument` when the input is not exactly 64
    /// hex digits (after an optional prefix), or when any character is
    /// not a hex digit.
    pub fn fromHex(s: []const u8) Error!Self {
        const body = if (s.len >= 2 and s[0] == '0' and (s[1] == 'x' or s[1] == 'X'))
            s[2..]
        else
            s;

        if (body.len != UID_HEX_LEN) return Error.InvalidArgument;

        var bytes: [UID_LEN]u8 = undefined;
        var i: usize = 0;
        while (i < UID_LEN) : (i += 1) {
            const hi = hexNibble(body[i * 2]) orelse return Error.InvalidArgument;
            const lo = hexNibble(body[i * 2 + 1]) orelse return Error.InvalidArgument;
            bytes[i] = (hi << 4) | lo;
        }
        return .{ .inner = .{ .bytes = bytes } };
    }

    // -------------------------------------------------------------------------
    // Inspection
    // -------------------------------------------------------------------------

    /// Copy the 32 bytes into a fresh array.
    pub fn toBytes(self: Self) [UID_LEN]u8 {
        return self.inner.bytes;
    }

    /// Return a read-only reference to the raw bytes.
    pub fn asBytes(self: Self) *const [UID_LEN]u8 {
        return &self.inner.bytes;
    }

    /// True when all 32 bytes are zero.
    pub fn isNull(self: Self) bool {
        for (self.inner.bytes) |b| {
            if (b != 0) return false;
        }
        return true;
    }

    /// Compare two UIDs by byte equality.
    ///
    /// `Uid` is a plain struct, so `==` works directly on values; this
    /// method exists for callers that prefer an explicit named check.
    pub fn eql(self: Self, other: Self) bool {
        return std.mem.eql(u8, &self.inner.bytes, &other.inner.bytes);
    }

    // -------------------------------------------------------------------------
    // ABI bridging
    // -------------------------------------------------------------------------

    /// Produce the argument-role struct that the native ABI expects.
    ///
    /// Used at every UID-addressed call site. Example:
    ///
    ///     sys.uidCall(uid.toLf(), param, timeout_ms)
    ///
    /// The returned value is a copy; the caller retains ownership of
    /// the original `Uid`.
    pub fn toLf(self: Self) sys.P2PUid {
        return self.inner;
    }

    /// Copy the 32 bytes out of a return-role pointer.
    ///
    /// The native pointer is valid for about 5 seconds and MUST NOT be
    /// retained. This function dereferences `ptr` immediately; the
    /// pointer is never stored or returned to the caller.
    ///
    /// # Safety
    ///
    /// `ptr` must point to a valid `sys.P2PUid` (32 readable bytes).
    /// The call sites in this binding always satisfy that contract
    /// because the pointer comes from `LF_Get_P2P_UID`, whose native
    /// implementation always allocates a well-formed struct.
    pub fn fromPtr(ptr: *const sys.P2PUid) Self {
        return .{ .inner = ptr.* };
    }

    // -------------------------------------------------------------------------
    // Hex output
    // -------------------------------------------------------------------------

    /// Encode the UID as 64 lowercase hex characters into `buf`.
    ///
    /// The output contains no prefix and no separators. This is the
    /// recommended way to produce a debug or log string:
    ///
    ///     var buf: [64]u8 = undefined;
    ///     uid.toHexBuf(&buf);
    ///     std.debug.print("uid = {s}\n", .{&buf});
    pub fn toHexBuf(self: Self, buf: *[UID_HEX_LEN]u8) void {
        var i: usize = 0;
        while (i < UID_LEN) : (i += 1) {
            const b = self.inner.bytes[i];
            buf[i * 2] = hexChar(b >> 4);
            buf[i * 2 + 1] = hexChar(b & 0x0F);
        }
    }

    /// Allocate a NUL-terminated 64-character hex string.
    ///
    /// The caller owns the returned slice and must free it with
    /// `alloc.free`.
    pub fn toHexAlloc(self: Self, alloc: std.mem.Allocator) Error![:0]u8 {
        var buf: [UID_HEX_LEN]u8 = undefined;
        self.toHexBuf(&buf);
        return util.dupeZ(alloc, &buf);
    }
};

// =============================================================================
// Internal hex helpers
// =============================================================================

/// Map a nibble value (0..=15) to its lowercase hex character.
///
/// The `else` arm is unreachable when the input comes from a `>> 4` or
/// `& 0x0F` operation, but is provided to keep the function total
/// without an `unreachable` assumption.
inline fn hexChar(n: u8) u8 {
    return switch (n) {
        0...9 => '0' + n,
        10...15 => 'a' + (n - 10),
        else => '?',
    };
}

/// Parse a single ASCII hex digit. Returns `null` for anything else.
inline fn hexNibble(b: u8) ?u8 {
    return switch (b) {
        '0'...'9' => b - '0',
        'a'...'f' => b - 'a' + 10,
        'A'...'F' => b - 'A' + 10,
        else => null,
    };
}

// =============================================================================
// Tests
// =============================================================================
//
// Every array-fill in these tests uses `@splat` rather than the `**`
// array-repeat operator. `@splat` is a builtin with no whitespace
// dependency; it cannot be broken by an editor or a text round-trip.
//
// There is no test for a `format` method because this module does not
// define one. See the module docstring for the rationale.

const testing = std.testing;

test "Uid.NULL is all zero" {
    const zeros: [UID_LEN]u8 = @splat(0);
    try testing.expect(Uid.NULL.isNull());
    try testing.expectEqual(zeros, Uid.NULL.toBytes());
}

test "fromBytes / toBytes roundtrip" {
    const bytes: [UID_LEN]u8 = @splat(1);
    const uid = Uid.fromBytes(bytes);
    try testing.expectEqual(bytes, uid.toBytes());
    try testing.expect(!uid.isNull());
}

test "fromSlice rejects wrong length" {
    const too_short: [UID_LEN - 1]u8 = @splat(0);
    const too_long: [UID_LEN + 1]u8 = @splat(0);

    try testing.expectError(Error.InvalidArgument, Uid.fromSlice(&too_short));
    try testing.expectError(Error.InvalidArgument, Uid.fromSlice(&too_long));
    try testing.expectError(Error.InvalidArgument, Uid.fromSlice(&[_]u8{}));
}

test "fromSlice accepts exact length" {
    const slice: [UID_LEN]u8 = @splat(0xAB);
    const uid = try Uid.fromSlice(&slice);
    try testing.expectEqual(slice, uid.toBytes());
}

test "fromHex / toHexBuf roundtrip (lowercase)" {
    const hex = "0123456789abcdef0123456789abcdef" ++
        "0123456789abcdef0123456789abcdef";
    const uid = try Uid.fromHex(hex);

    var buf: [UID_HEX_LEN]u8 = undefined;
    uid.toHexBuf(&buf);
    try testing.expectEqualStrings(hex, &buf);
}

test "fromHex accepts uppercase" {
    const upper = "0123456789ABCDEF0123456789ABCDEF" ++
        "0123456789ABCDEF0123456789ABCDEF";
    const lower = "0123456789abcdef0123456789abcdef" ++
        "0123456789abcdef0123456789abcdef";

    const uid = try Uid.fromHex(upper);

    var buf: [UID_HEX_LEN]u8 = undefined;
    uid.toHexBuf(&buf);
    try testing.expectEqualStrings(lower, &buf);
}

test "fromHex accepts a 0x prefix" {
    const hex = "0x0123456789abcdef0123456789abcdef" ++
        "0123456789abcdef0123456789abcdef";
    const uid = try Uid.fromHex(hex);
    try testing.expect(!uid.isNull());
}

test "fromHex accepts an 0X prefix" {
    const hex = "0X0123456789abcdef0123456789abcdef" ++
        "0123456789abcdef0123456789abcdef";
    const uid = try Uid.fromHex(hex);
    try testing.expect(!uid.isNull());
}

test "fromHex rejects wrong length" {
    // Empty and short literals.
    try testing.expectError(Error.InvalidArgument, Uid.fromHex(""));
    try testing.expectError(Error.InvalidArgument, Uid.fromHex("abc"));

    // Build a short and a long buffer with `@splat`, avoiding the
    // string-repeat operator.
    const short: [UID_HEX_LEN - 1]u8 = @splat('a');
    const long: [UID_HEX_LEN + 1]u8 = @splat('a');

    try testing.expectError(Error.InvalidArgument, Uid.fromHex(&short));
    try testing.expectError(Error.InvalidArgument, Uid.fromHex(&long));
}

test "fromHex rejects non-hex characters" {
    const bad: [UID_HEX_LEN]u8 = @splat('z');
    try testing.expectError(Error.InvalidArgument, Uid.fromHex(&bad));
}

test "toLf returns a struct with the same bytes" {
    const hex = "0123456789abcdef0123456789abcdef" ++
        "0123456789abcdef0123456789abcdef";
    const uid = try Uid.fromHex(hex);
    const lf = uid.toLf();
    try testing.expectEqual(uid.toBytes(), lf.bytes);
}

test "fromPtr copies the bytes immediately" {
    var backing: sys.P2PUid = .{ .bytes = @splat(0x42) };
    const uid = Uid.fromPtr(&backing);
    try testing.expectEqual(@as(u8, 0x42), uid.toBytes()[0]);

    // Mutating the source after fromPtr must not affect the copy.
    backing.bytes[0] = 0x99;
    try testing.expectEqual(@as(u8, 0x42), uid.toBytes()[0]);
}

test "toHexAlloc produces a NUL-terminated string" {
    const alloc = testing.allocator;

    const hex = "0123456789abcdef0123456789abcdef" ++
        "0123456789abcdef0123456789abcdef";
    const uid = try Uid.fromHex(hex);
    const out = try uid.toHexAlloc(alloc);
    defer alloc.free(out);

    try testing.expectEqual(@as(usize, UID_HEX_LEN), out.len);
    try testing.expectEqual(@as(u8, 0), out[out.len]);
    try testing.expectEqualStrings(hex, out);
}

test "eql compares by byte content" {
    const a = try Uid.fromHex(
        "0123456789abcdef0123456789abcdef" ++
            "0123456789abcdef0123456789abcdef",
    );
    const b = try Uid.fromHex(
        "0123456789abcdef0123456789abcdef" ++
            "0123456789abcdef0123456789abcdef",
    );
    const c = try Uid.fromHex(
        "ffffffffffffffffffffffffffffffff" ++
            "ffffffffffffffffffffffffffffffff",
    );

    try testing.expect(a.eql(b));
    try testing.expect(!a.eql(c));
    try testing.expect(!a.eql(Uid.NULL));
}
